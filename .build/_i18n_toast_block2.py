def patch_security_page():
    path = ROOT / "src/app/dashboard/security/page.tsx"
    text = path.read_text(encoding="utf-8")
    if "useApiErrorMessage" not in text:
        text = text.replace(
            "import { useTranslations } from 'next-intl';",
            "import { useTranslations } from 'next-intl';\nimport { useApiErrorMessage } from '@/hooks/useApiErrorMessage';",
        )
    if "const tn = useTranslations('common.notifications')" not in text:
        text = text.replace(
            "  const ta = useTranslations('account');",
            "  const ta = useTranslations('account');\n  const tn = useTranslations('common.notifications');\n  const tt = useTranslations('account.toasts');\n  const { fromApi } = useApiErrorMessage();",
        )
    for old, new in SECURITY_REPLACEMENTS:
        if old not in text:
            print(f"WARN missing in security page: {old[:60]}...")
        else:
            text = text.replace(old, new)
    # new address lock block
    text = text.replace(
        "title: next ? 'New address lock enabled' : 'New address lock disabled',\n          description: next\n            ? 'Withdrawals to newly saved addresses are blocked for 24 hours.'\n            : 'New address 24h withdrawal lock turned off.',",
        "title: next ? tt('newAddressLockEnabledTitle') : tt('newAddressLockDisabledTitle'),\n          description: next\n            ? tt('newAddressLockEnabledDesc')\n            : tt('newAddressLockDisabledDesc'),",
    )
    path.write_text(text, encoding="utf-8")


def patch_file_replacements(rel_path: str, replacements: list[tuple[str, str]], hooks: str | None = None):
    path = ROOT / rel_path
    text = path.read_text(encoding="utf-8")
    if hooks and hooks not in text:
        # hooks is snippet to insert after 'use client' imports block - caller handles
        pass
    for old, new in replacements:
        if old in text:
            text = text.replace(old, new)
        else:
            print(f"WARN {rel_path}: missing {old[:50]}")
    path.write_text(text, encoding="utf-8")


